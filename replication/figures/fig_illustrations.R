## fig_illustrations.R -- the illustrative TikZ figures of the main paper: Figure 1 (fig-thresholds.tex), Figure 2
## (fig-scalefam.tex) and Figure 3 (fig-geometry.tex), in the layout of the Bayesian Analysis template.
## Figures 1 and 2 are closed-form curves; Figure 3 adds simulated samples of size 1000 (seeded).
## Run from this folder: Rscript fig_illustrations.R. Needs the star package (rho_star, rstar).
suppressMessages(library(star))
fmt <- function(v) sprintf("%.3f", v)
coords <- function(x, y) paste(sprintf("(%s,%s)", fmt(x), fmt(y)), collapse = " ")
curve_line <- function(pre, xy, post = "") paste0(pre, "plot coordinates {", coords(xy[, 1], xy[, 2]), "}", post)
tau <- function(w) pmin(w, 1 - w) / pmax(w, 1 - w)
sig <- function(w, chib, nu) 1 + chib * tau(w)^(1 + nu)          # the scale family (6)
nu_inc <- function(w) 0.12 * (5 / 0.12)^w                          # increasing relaxation, log-linear from 0.12 to 5
W81 <- seq(0.004, 0.996, length.out = 81)
thr <- function(u1, u2, p, w = seq(0.002, 0.998, length.out = 81)) { r <- rho_star(w, u1, u2, p); cbind(r * w, r * (1 - w)) }
prof <- function(s) cbind(W81, s)                                  # scale profile sigma(w)
lset <- function(s) cbind(s * W81, s * (1 - W81))                 # limit set boundary sigma(w) (w, 1 - w)


