## samples of size 1000 on standard exponential margins, divided by log(1000): independence, a Gaussian copula
## with correlation 0.5, and the model at chibar = 1 with nu = 0.25 (threshold anchors 0.55 log n, exponent 8)
W61 <- seq(0.002, 0.998, length.out = 61)
lset61 <- function(s) cbind(s * W61, s * (1 - W61))
n <- 1000; ln <- log(n)
set.seed(20260928)
gauss <- function(n, r) { z1 <- rnorm(n); z2 <- r * z1 + sqrt(1 - r^2) * rnorm(n); cbind(-log(pnorm(-z1)), -log(pnorm(-z2))) }
SAMPLES <- list(indep = cbind(rexp(n), rexp(n)) / ln, gauss = gauss(n, 0.5) / ln,
  model = rstar(n, list(phi = rep(0.2, 5), alpha = 2, b = c(0, 0, 0), u1 = 0.55 * ln, u2 = 0.55 * ln, p = 8, chibar = 1, z = rep(log(0.25), 3)))$E / ln)
pts <- function(X) sprintf("\\fill[gray!60] (%s,%s) circle (0.28pt);", fmt(X[, 1]), fmt(X[, 2]))
